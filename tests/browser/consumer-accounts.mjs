import { expect } from '@playwright/test'

export async function verifyConsumerAccounts(page, url, screenshot) {
  const visit = panel => page.goto(`${url}?page=consumer-accounts&panel=${panel}`)
  const delay = (key, failure = false) => page.evaluate(({ key, failure }) => {
    window.workspaceFixture.operations.delays[key] = 700
    if (failure) window.workspaceFixture.operations.failures[key] = 1
  }, { key, failure })
  async function blocked(dialog) {
    await expect(dialog.getByRole('button', { name: '关闭弹窗', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
  }
  const loginRequests = []
  await page.route('**/api/auth/sign-in/username', async route => {
    loginRequests.push(route.request().postDataJSON())
    await route.fulfill({ status: 401, json: { code: 'INVALID_CREDENTIALS', message: 'fixture' } })
  })
  await visit('login')
  const remember = page.getByRole('checkbox', { name: '保持登录', exact: true })
  await expect(remember).toBeChecked()
  await remember.focus(); await page.keyboard.press('Space')
  await expect(remember).not.toBeChecked()
  await expect(remember).toHaveAttribute('name', 'remember-me')
  await page.getByRole('textbox', { name: '账号或邮箱', exact: true }).fill('fixture-user')
  await page.getByRole('textbox', { name: '密码', exact: true }).fill('fixture-password')
  const loginPassword = page.getByRole('textbox', { name: '密码', exact: true })
  await loginPassword.evaluate(input => input.setSelectionRange(2, 6))
  await page.getByRole('button', { name: '显示密码', exact: true }).click()
  await expect(loginPassword).toHaveAttribute('type', 'text')
  expect(await loginPassword.evaluate(input => [input.selectionStart, input.selectionEnd])).toEqual([2, 6])
  await page.getByRole('button', { name: '隐藏密码', exact: true }).click()
  await expect(loginPassword).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('账号或密码不正确')
  expect(loginRequests).toMatchObject([{ username: 'fixture-user', rememberMe: false }])
  await page.unroute('**/api/auth/sign-in/username')

  await visit('tokens')
  await page.getByRole('button', { name: '创建凭证', exact: true }).click()
  const token = page.getByRole('dialog')
  await expect(token.getByRole('textbox', { name: '凭证名称', exact: true })).toBeFocused()
  await token.getByRole('textbox', { name: '凭证名称', exact: true }).fill('下游组件回归')
  await delay('POST:/api/account/agent-tokens', true)
  await token.getByRole('button', { name: '创建凭证', exact: true }).click()
  await blocked(token)
  await expect(token.getByRole('alert')).toBeVisible()
  await expect(token.getByRole('button', { name: '取消', exact: true })).toBeEnabled()
  await token.getByRole('button', { name: '创建凭证', exact: true }).click()
  await expect(token).toHaveAccessibleName('凭证已创建')
  await expect(token.getByRole('textbox', { name: '新建 AI 凭证', exact: true })).toHaveValue('fixture-only-not-a-valid-token')
  for (const theme of ['light', 'dark']) {
    await page.locator('html').evaluate((node, theme) => node.dataset.bingTheme = theme, theme)
    await page.setViewportSize({ width: 390, height: 500 })
    await expect(token.getByRole('button', { name: '完成', exact: true })).toBeInViewport()
    await screenshot(`consumer-account-${theme}`)
  }
  await token.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '撤销 下游组件回归', exact: true }).click()
  await token.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '撤销 下游组件回归', exact: true }).click()
  await token.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(token).toHaveCount(0)
  await expect(page.getByRole('button', { name: '撤销 下游组件回归', exact: true })).toHaveCount(0)

  await visit('invitations')
  await page.getByRole('button', { name: '新增用户', exact: true }).click()
  const invitation = page.getByRole('dialog')
  await invitation.getByRole('tab', { name: '邀请加入', exact: true }).click()
  await invitation.getByRole('textbox', { name: '姓名', exact: true }).fill('邀请回归')
  await invitation.getByRole('textbox', { name: '邮箱', exact: true }).fill('fixture@example.test')
  await invitation.getByText('开发', { exact: true }).click()
  await invitation.getByText('测试', { exact: true }).click()
  await expect(invitation.getByRole('checkbox', { name: '开发', exact: true })).toBeChecked()
  await expect(invitation.getByRole('checkbox', { name: '测试', exact: true })).toBeChecked()
  await delay('POST:/api/admin/invitations')
  await invitation.getByRole('button', { name: '生成邀请链接', exact: true }).click()
  await blocked(invitation)
  await expect(invitation.getByRole('textbox', { name: '邀请链接', exact: true })).toHaveValue('https://example.test/invite/fixture')
  expect(await page.evaluate(() => window.workspaceFixture.operations.requests.find(item => item.key === 'POST:/api/admin/invitations').body.roles)).toEqual(['developer', 'qa'])
  await invitation.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '新增用户', exact: true }).click()
  await expect(invitation.getByRole('checkbox', { name: '开发', exact: true })).not.toBeChecked()
  await invitation.getByRole('button', { name: '取消', exact: true }).click()

  await page.route('**/api/auth/change-password', async route => {
    await new Promise(resolve => setTimeout(resolve, 700))
    await route.fulfill({ json: { token: null, user: { id: 'fixture-user' } } })
  })
  await visit('password')
  await page.getByRole('button', { name: '修改密码', exact: true }).last().click()
  const password = page.getByRole('dialog', { name: '修改密码', exact: true })
  await expect(password.getByRole('textbox', { name: '当前密码', exact: true })).toBeFocused()
  for (const name of ['当前密码', '新密码', '确认新密码']) await password.getByRole('textbox', { name, exact: true }).fill('fixture-password')
  await password.getByRole('button', { name: '保存新密码', exact: true }).click()
  await blocked(password)
  await expect(password.getByRole('status').filter({ hasText: '密码已修改' })).toBeVisible()
  await password.getByRole('button', { name: '完成', exact: true }).click()
  await page.unroute('**/api/auth/change-password')
  console.log('通过：真实登录表单的保持登录/空格/提交，凭证创建失败恢复与关闭保护、结果/撤销、邀请角色多选及重开清空、修改密码焦点和 busy，390×500 亮暗布局；接口均为受控响应。')
}
