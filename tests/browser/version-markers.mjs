  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const longBase = { type: 'doc', content: Array.from({ length: 50 }, (_, i) => p(`long-${i}`, `正文第 ${i} 段，布局测量保持贴合。`)) }
