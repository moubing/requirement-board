import { expect } from '@playwright/test'
import { verifyFontSettings } from './font-settings.mjs'

export async function verifyAppSettings(page, url, screenshot) {
  const originalViewport = page.viewportSize()
  await page.setViewportSize({ width: 1440, height: 1024 })
  const original = await page.evaluate(() => JSON.stringify(window.workspaceFixture.document()))
  const paragraph = page.locator('.tiptap p').first()
  const initialTypography = await paragraph.evaluate(element => {
    const style = getComputedStyle(element)
    return [style.fontSize, style.color, style.lineHeight]
  })
  const trigger = page.getByRole('button', { name: '设置', exact: true })
  const dialog = page.getByRole('dialog', { name: '设置', exact: true })
  const cursor = () => page.locator('[data-bing-cursor-native]').evaluateAll(elements => elements.map(element => getComputedStyle(element).cursor).join(' '))
  await trigger.hover()
  await expect.poll(cursor).not.toContain('url(')
  await trigger.click()
  await expect(dialog).toBeVisible()
  await dialog.locator('.app-settings__theme-preview[data-preview-theme="dark"]').click()
  await expect(page.locator('html')).toHaveAttribute('data-bing-theme', 'dark')
  await dialog.locator('.app-settings__theme-preview[data-preview-theme="system"]').click()
  await expect(dialog.getByRole('radio', { name: '跟随系统', exact: true })).toBeChecked()
  await expect(dialog.getByRole('checkbox', { name: '启用自定义指针' })).not.toBeChecked()
  await dialog.getByText('启用自定义指针', { exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '启用自定义指针' })).toBeChecked()
  await expect.poll(cursor).toContain('url(')
  // 新默认值不能覆盖已经保存的开启状态。
  await page.reload()
  await expect(paragraph).toBeVisible()
  await trigger.hover()
  await expect.poll(cursor).toContain('url(')
  await trigger.click()
  await expect(dialog.getByRole('checkbox', { name: '启用自定义指针' })).toBeChecked()
  await dialog.getByText('启用自定义指针', { exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '启用自定义指针' })).not.toBeChecked()
  await expect.poll(cursor).not.toContain('url(')
  await screenshot('settings-global')

  async function chooseTheme(label) {
    await dialog.getByRole('tab', { name: '外观与交互', exact: true }).click()
    await dialog.getByRole('radio', { name: label, exact: true }).focus()
    await page.keyboard.press('Space')
  }
  async function editorTab() { await dialog.getByRole('tab', { name: '阅读与编辑', exact: true }).click() }
  async function changeColor(label, theme, hex) {
    const beforeTheme = await page.locator('html').getAttribute('data-bing-theme')
    await dialog.getByRole('combobox', { name: '编辑文字配色', exact: true }).click()
    await page.getByRole('option', { name: `${theme}配色`, exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-bing-theme', beforeTheme)
    await dialog.getByRole('button', { name: `${label}颜色（${theme}）`, exact: true }).click()
    const panel = page.getByRole('dialog', { name: `${label}颜色（${theme}）`, exact: true })
    await panel.getByRole('textbox', { name: '颜色值', exact: true }).fill(hex)
    await panel.getByRole('textbox', { name: '颜色值', exact: true }).press('Enter')
    await dialog.locator('.app-settings__preview-label').first().click()
    await expect(panel).toBeHidden()
    await expect(dialog).toBeVisible()
  }
  await chooseTheme('亮色')
  async function frame() {
    const elements = [dialog, dialog.getByRole('tablist', { name: '设置分类', exact: true }), dialog.getByRole('button', { name: '恢复本页默认', exact: true }), dialog.getByRole('button', { name: '完成', exact: true })]
    return Promise.all(elements.map(element => element.boundingBox()))
  }
  const initialFrame = await frame()
  expect(initialFrame[0].height).toBe(600)
  expect(initialFrame[0].width).toBe(900)
  await editorTab()
  expect(await frame()).toEqual(initialFrame)
  await expect(dialog.getByRole('combobox', { name: '编辑文字配色', exact: true })).toContainText('亮色配色')
  await screenshot('settings-editor-default')
  await dialog.getByRole('slider', { name: '辅助面板宽度滑杆', exact: true }).scrollIntoViewIfNeeded()
  expect(await frame()).toEqual(initialFrame)
  await screenshot('settings-layout-default')
  for (const [label, size] of [['一级标题', 36], ['二级标题', 28], ['三级标题', 22], ['段落', 18]]) {
    await dialog.getByRole('spinbutton', { name: `${label}字号`, exact: true }).fill(String(size))
  }
  await dialog.getByRole('spinbutton', { name: '正文行高', exact: true }).fill('2')
  await dialog.getByRole('spinbutton', { name: '正文最大宽度', exact: true }).fill('920')
  await dialog.getByRole('spinbutton', { name: '辅助面板宽度', exact: true }).fill('440')
  await expect(dialog.getByRole('slider', { name: '辅助面板宽度滑杆', exact: true })).toHaveValue('440')
  await changeColor('段落', '亮色', '#33445580')
  await changeColor('一级标题', '亮色', '#4f46e5')
  await expect(paragraph).toHaveCSS('font-size', '18px')
  await expect(paragraph).toHaveCSS('line-height', '36px')
  await expect(paragraph).toHaveCSS('color', 'rgba(51, 68, 85, 0.5)')
  await expect(page.locator('.tiptap h1').first()).toHaveCSS('font-size', '36px')
  await expect(page.locator('.tiptap h1').first()).toHaveCSS('color', 'rgb(79, 70, 229)')
  await expect(page.locator('.tiptap h3').first()).toHaveCSS('font-size', '22px')
  await expect(page.locator('.app-settings-preview h2')).toHaveCSS('font-size', '28px')
  await expect(page.locator('.tiptap')).toHaveCSS('max-width', '920px')
  await expect(dialog.getByRole('heading', { name: '设置', exact: true })).not.toHaveCSS('font-size', '36px')
  await screenshot('settings-editor-light')
  for (let index = 0; index < 3; index++) {
    await dialog.getByRole('tab', { name: '外观与交互', exact: true }).click()
    expect(await frame()).toEqual(initialFrame)
    await editorTab()
    expect(await frame()).toEqual(initialFrame)
  }

  await chooseTheme('暗色')
  await expect(page.locator('html')).toHaveAttribute('data-bing-theme', 'dark')
  await expect(paragraph).toHaveCSS('color', 'rgb(237, 240, 245)')
  await editorTab()
  await changeColor('段落', '暗色', '#cbd5e1')
  await expect(paragraph).toHaveCSS('color', 'rgb(203, 213, 225)')
  await screenshot('settings-editor-dark')
  await chooseTheme('跟随系统')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(paragraph).toHaveCSS('color', 'rgba(51, 68, 85, 0.5)')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(paragraph).toHaveCSS('color', 'rgb(203, 213, 225)')
  await chooseTheme('亮色')
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => JSON.stringify(window.workspaceFixture.document()))).toBe(original)

  await page.getByRole('tab', { name: '版本比较', exact: true }).click()
  await expect(page.locator('.diff-block p.diff-block__text').first()).toHaveCSS('font-size', '18px')
  await expect(page.locator('.diff-block p.diff-block__text').first()).toHaveCSS('line-height', '36px')
  await expect(page.locator('.diff-block h1.diff-block__text').first()).toHaveCSS('color', 'rgb(79, 70, 229)')
  await screenshot('settings-diff')

  await page.goto(url)
  await expect(paragraph).toHaveCSS('font-size', '18px')
  await expect(paragraph).toHaveCSS('color', 'rgba(51, 68, 85, 0.5)')
  await expect(page.locator('.tiptap')).toHaveCSS('max-width', '920px')
  await trigger.hover()
  await expect.poll(cursor).not.toContain('url(')
  await trigger.click()
  await editorTab()
  await expect(dialog.getByRole('spinbutton', { name: '段落字号', exact: true })).toHaveValue('18')
  await expect(dialog.getByRole('spinbutton', { name: '辅助面板宽度', exact: true })).toHaveValue('440')

  // 中间输入不强制截断；失焦校正范围，空值恢复默认。
  const size = dialog.getByRole('spinbutton', { name: '段落字号', exact: true })
  await size.fill('2')
  await expect(paragraph).toHaveCSS('font-size', '18px')
  await size.press('End')
  await size.press('4')
  await expect(paragraph).toHaveCSS('font-size', '24px')
  await size.fill('999')
  await size.press('Tab')
  await expect(size).toHaveValue('32')
  await size.fill('')
  await size.press('Tab')
  await expect(paragraph).toHaveCSS('font-size', initialTypography[0])
  await dialog.getByRole('button', { name: '段落颜色跟随主题', exact: true }).click()
  await expect(paragraph).toHaveCSS('color', initialTypography[1])

  const panelWidth = dialog.getByRole('spinbutton', { name: '辅助面板宽度', exact: true })
  await panelWidth.fill('5')
  await expect(dialog.getByRole('slider', { name: '辅助面板宽度滑杆', exact: true })).toHaveValue('440')
  await panelWidth.fill('999'); await panelWidth.press('Enter')
  await expect(panelWidth).toHaveValue('560')
  const panelSlider = dialog.getByRole('slider', { name: '辅助面板宽度滑杆', exact: true })
  await panelSlider.focus(); await panelSlider.press('Home')
  await expect(panelWidth).toHaveValue('320')
  await panelSlider.locator('xpath=ancestor::*[contains(@class,"bing-slider")][1]').locator('.bing-slider__thumb').dblclick()
  await expect(panelWidth).toHaveValue('360')
  await panelSlider.press('Home')
  await expect(dialog.getByRole('spinbutton', { name: '正文最大宽度', exact: true })).toHaveValue('920')
  await dialog.getByRole('button', { name: '恢复辅助面板默认宽度', exact: true }).click()
  await expect(panelWidth).toHaveValue('360')
  // 浏览器静默拒绝 Cookie 时，当前预览继续生效但不能显示保存成功。
  await page.evaluate(() => Object.defineProperty(document, 'cookie', { configurable: true, get: () => '', set: () => {} }))
  await panelWidth.fill('450')
  await expect(dialog.getByRole('alert')).toContainText('尚未保存')
  await expect(panelSlider).toHaveValue('450')
  await page.evaluate(() => { delete document.cookie })
  await dialog.getByRole('button', { name: '重试保存', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveCount(0)

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(dialog).toBeVisible()
  const box = await dialog.boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(390)
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  for (const element of await dialog.locator('.app-settings__text-row > *').all()) {
    const rect = await element.boundingBox()
    expect(rect.x + rect.width).toBeLessThanOrEqual(box.x + box.width)
  }
  await dialog.getByRole('spinbutton', { name: '正文最大宽度', exact: true }).fill('1000')
  await screenshot('settings-mobile')
  await dialog.getByRole('button', { name: '恢复本页默认', exact: true }).click()
  await expect(dialog.getByRole('spinbutton', { name: '正文最大宽度', exact: true })).toHaveValue('880')
  await expect(panelWidth).toHaveValue('360')
  await expect(page.locator('html')).toHaveAttribute('data-bing-theme', 'light')
  await dialog.getByRole('tab', { name: '外观与交互', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '启用自定义指针' })).not.toBeChecked()
  await dialog.getByRole('button', { name: '恢复本页默认', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '启用自定义指针' })).not.toBeChecked()
  for (const viewport of [{ width: 390, height: 500 }, { width: 320, height: 500 }]) {
    await page.setViewportSize(viewport)
    // Dialog 在 visualViewport 的下一帧更新可用高度，先等尺寸收敛再比较切页布局。
    await expect.poll(async () => (await dialog.boundingBox()).height).toBe(viewport.height)
    const compactFrame = await frame()
    await editorTab()
    expect(await frame()).toEqual(compactFrame)
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await expect(dialog.getByRole('button', { name: '完成', exact: true })).toBeInViewport()
    await screenshot(`settings-fixed-${viewport.width}`)
    await dialog.getByRole('tab', { name: '外观与交互', exact: true }).click()
  }
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await page.setViewportSize(originalViewport)
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto(url)
  await expect(paragraph).toHaveCSS('font-size', initialTypography[0])
  await expect(paragraph).toHaveCSS('color', initialTypography[1])
  await expect(paragraph).toHaveCSS('line-height', initialTypography[2])
  await expect(page.locator('html')).toHaveAttribute('data-bing-theme', 'system')
  await expect(page.locator('html')).toHaveAttribute('data-editor-sizes', '')
  await expect(page.locator('html')).toHaveAttribute('data-editor-colors', '')
  await trigger.hover()
  await expect.poll(cursor).not.toContain('url(')
  expect(await page.evaluate(() => JSON.stringify(window.workspaceFixture.document()))).toBe(original)
  console.log('设置无头验证通过：固定 900×600 框架、两类分组恢复、独立亮暗配色、双宽度/滑杆、存储失败、半成品输入、正文/Diff 保留及 320×500 适配。')
  await verifyFontSettings(page, url, screenshot)
}
