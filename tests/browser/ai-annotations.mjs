        const firstTop = Math.min(...marks.map(rect => rect.top)), firstLeft = Math.min(...marks.map(rect => rect.left))
        const viewport = await body.boundingBox()
        return input && badge && input.y + input.height <= firstTop - 4 && input.y + input.height >= firstTop - 16
          && badge.y + badge.height <= firstTop && badge.x < firstLeft && badge.x >= viewport.x
          && !marks.some(rect => rect.left < badge.x + badge.width && rect.right > badge.x && rect.top < badge.y + badge.height && rect.bottom > badge.y)
