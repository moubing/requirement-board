import { expect } from '@playwright/test'

async function verifyDocumentTopbar(page, screenshot) {
  const properties = page.getByRole('region', { name: '文档常用属性', exact: true })
  const owner = properties.getByRole('combobox', { name: '负责人', exact: true })
  const priority = properties.getByRole('combobox', { name: '优先级', exact: true })
  const assertSingleRow = async () => {
    await expect(owner).toBeVisible()
    const [nav, attributes, save, more, header, toolbar] = await Promise.all([
      page.getByRole('navigation', { name: '文档工作区' }).boundingBox(), properties.boundingBox(),
      page.getByRole('button', { name: '保存版本', exact: true }).boundingBox(),
      page.getByRole('button', { name: '更多文档操作', exact: true }).boundingBox(),
      page.locator('.requirement-topbar').boundingBox(), page.locator('.requirement-editor__toolbar').boundingBox(),
    ])
    for (const rect of [attributes, save, more]) expect(Math.abs(rect.y + rect.height / 2 - nav.y - nav.height / 2)).toBeLessThan(1)
    expect(attributes.x).toBeGreaterThanOrEqual(nav.x + nav.width)
    expect(save.x).toBeGreaterThanOrEqual(attributes.x + attributes.width)
    expect(more.x).toBeGreaterThanOrEqual(save.x + save.width)
    expect(header.height).toBeLessThanOrEqual(68)
    expect(Math.abs(toolbar.y - header.y - header.height)).toBeLessThan(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  await page.evaluate(() => document.fonts.ready)
  const availableWidth = await page.locator('.requirement-page').evaluate(el => el.clientWidth)
  const fullControlsBoundary = 1440 - availableWidth + 1120
  for (const width of [1525, 1440, fullControlsBoundary]) {
    await page.setViewportSize({ width, height: 1000 })
    await assertSingleRow()
    if (width === 1525) await screenshot('detail-topbar-prototype-1525')
  }
  await page.setViewportSize({ width: fullControlsBoundary - 1, height: 1000 })
  await expect(properties.getByRole('button', { name: '文档属性', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  const before = await page.evaluate(() => ({ body: JSON.stringify(window.workspaceFixture.document()), versions: window.workspaceFixture.revisions.value.length }))
  await page.evaluate(() => {
    const f = window.workspaceFixture
    const assignees = [f.requirement.value.assignees[0],
      { id: 'long-owner-a', name: '前端同学（负责交互与公共组件开发）', avatarColor: '#417a55' },
      { id: 'long-owner-b', name: '测试同学（负责接口与页面验收）', avatarColor: '#a06424' }]
    f.requirement.value = { ...f.requirement.value, assignees, assigneeIds: assignees.map(user => user.id) }
    f.draft.participants.value = assignees.map(user => ({ ...user, color: user.avatarColor }))
    f.metadataRequests.length = 0
  })
  await assertSingleRow()
  await page.setViewportSize({ width: fullControlsBoundary, height: 1000 })
  await assertSingleRow()
  for (const width of [1024, 978, 977, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(properties.getByRole('button', { name: '文档属性', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    expect((await page.locator('.requirement-topbar').boundingBox()).height).toBeLessThanOrEqual(116)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await owner.click()
  await page.getByRole('option', { name: '测试成员', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.assigneeIds)).toEqual(['long-owner-a', 'long-owner-b'])
  expect(await page.evaluate(() => window.workspaceFixture.metadataRequests.filter(request => request.method === 'PATCH').length)).toBe(1)
  await expect(owner).toContainText('前端同学')
  await owner.press('Enter')
  await page.getByRole('option', { name: '测试成员', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.assigneeIds.length)).toBe(3)
  // 成功提示位于顶部中央，可能盖住属性栏；先逐条关闭，不依赖状态名称宽度决定的控件位置。
  const notices = page.getByRole('region', { name: '消息通知' }).getByRole('button', { name: '关闭消息' })
  for (let count = await notices.count(); count > 0; count--) {
    await notices.first().click()
    await expect(notices).toHaveCount(count - 1)
  }
  await page.evaluate(() => window.workspaceFixture.failMetadata())
  await priority.click()
  await page.getByRole('option', { name: '低', exact: true }).click()
  await expect(page.locator('.requirement-meta-error')).toContainText('当前选择尚未生效')
  await expect(priority).toContainText('低优先级')
  expect(await page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('high')
  await page.getByRole('button', { name: '重试保存属性', exact: true }).click()
  await expect(page.locator('.requirement-meta-error')).toBeHidden()
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('low')
  expect(await page.evaluate(() => JSON.stringify(window.workspaceFixture.document()))).toBe(before.body)
  expect(await page.evaluate(() => window.workspaceFixture.revisions.value.length)).toBe(before.versions)
  await page.evaluate(() => document.documentElement.dataset.bingTheme = 'dark')
  await assertSingleRow()
  await screenshot('detail-topbar-dark-long-owners')
  await page.evaluate(() => document.documentElement.dataset.bingTheme = 'light')
}

export async function verifyDocumentLayout(page, url, screenshot) {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(url)
  await verifyDocumentTopbar(page, screenshot)
  await page.goto(url)
  const separator = page.getByRole('separator', { name: '调整文档辅助面板宽度' })
  const body = page.getByRole('region', { name: '文档正文', exact: true })
  const side = page.locator('.requirement-side')
  await expect(page.getByRole('tab', { name: '目录', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(separator).toHaveAttribute('aria-valuenow', '360')
  await page.evaluate(() => { window.layoutEditor = document.querySelector('.tiptap'); window.layoutBody = JSON.stringify(window.workspaceFixture.document()) })
  await page.locator('[data-outline-id="heading_4"]').click()
  await expect.poll(() => body.evaluate(el => el.scrollTop)).toBeGreaterThan(1000)
  await page.evaluate(() => {
    const editor = document.querySelector('.tiptap').editor
    let position = 1
    editor.state.doc.descendants((node, pos) => { if (node.attrs.diffId === 'paragraph_4_0') position = pos + 1 })
    editor.commands.setTextSelection({ from: position, to: position + 6 })
    window.layoutSelection = editor.state.selection.toJSON()
  })
  await page.evaluate(() => {
    const viewport = document.querySelector('[aria-label="文档正文"]')
    const top = viewport.getBoundingClientRect().top
    const element = [...document.querySelectorAll('.tiptap [data-diff-id]')].find(el => el.getBoundingClientRect().bottom > top + 1)
    window.layoutAnchor = { element, offset: element.getBoundingClientRect().top - top }
  })
  const anchorDelta = () => page.evaluate(() => Math.abs(window.layoutAnchor.element.getBoundingClientRect().top - document.querySelector('[aria-label="文档正文"]').getBoundingClientRect().top - window.layoutAnchor.offset))
  await separator.focus(); await page.keyboard.press('End')
  await expect(separator).toHaveAttribute('aria-valuenow', '560')
  await expect.poll(anchorDelta).toBeLessThan(2)
  await separator.press('Home')
  await expect(separator).toHaveAttribute('aria-valuenow', '320')
  await expect.poll(anchorDelta).toBeLessThan(2)
  await separator.press('Enter')
  await expect(separator).toHaveAttribute('aria-valuenow', '360')
  const box = await separator.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + 60); await page.mouse.down()
  await page.mouse.move(box.x - 80, box.y + 60, { steps: 6 })
  await expect.poll(() => side.evaluate(el => el.clientWidth)).toBeGreaterThan(400)
  await page.keyboard.press('Escape'); await page.mouse.up()
  await expect(separator).toHaveAttribute('aria-valuenow', '360')
  await expect.poll(anchorDelta).toBeLessThan(2)
  await separator.press('End')
  const compressedWindowWidth = await page.evaluate(() => innerWidth - document.querySelector('.requirement-page').clientWidth + 958)
  await page.setViewportSize({ width: compressedWindowWidth, height: 1000 })
  await expect.poll(() => side.evaluate(el => el.clientWidth)).toBeLessThanOrEqual(358)
  expect(await page.evaluate(() => JSON.parse(decodeURIComponent(document.cookie.split('; ').find(x => x.startsWith('rb-preferences=')).split('=').slice(1).join('='))).editor.panelWidth)).toBe(560)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(separator).toHaveAttribute('aria-valuenow', '560')
  await separator.press('Enter')
  await expect.poll(anchorDelta).toBeLessThan(2)
  expect(await page.evaluate(() => window.layoutEditor === document.querySelector('.tiptap'))).toBe(true)
  expect(await page.evaluate(() => document.querySelector('.tiptap').editor.state.selection.toJSON())).toEqual(await page.evaluate(() => window.layoutSelection))
  expect(await page.evaluate(() => JSON.stringify(window.workspaceFixture.document()) === window.layoutBody)).toBe(true)
  await screenshot('detail-docked-1440')

  const dockWidth = await page.evaluate(() => innerWidth - document.querySelector('.requirement-page').clientWidth + 920)
  for (const width of [dockWidth, dockWidth - 1, 1024, 960, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    if (width === dockWidth) await expect(side).toBeVisible()
    else {
      await expect(side).toHaveCount(0)
      await expect(page.getByRole('button', { name: '文档属性', exact: true })).toBeVisible()
      await page.getByRole('button', { name: '打开文档信息和目录' }).click()
      const drawer = page.getByRole('dialog', { name: '文档辅助面板', exact: true })
      await expect(drawer.getByRole('tab', { name: '文档信息', exact: true })).toBeVisible()
      await drawer.getByRole('button', { name: '收起文档辅助面板' }).click()
      await expect(drawer).toBeHidden()
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    expect((await page.locator('.requirement-topbar').boundingBox()).height).toBeLessThanOrEqual(116)
  }
  await screenshot('detail-mobile-320')
  await page.setViewportSize({ width: 320, height: 500 })
  await expect.poll(async () => { const rect = await body.boundingBox(); return rect.y + rect.height }).toBeLessThanOrEqual(500)
  expect((await body.boundingBox()).height).toBeGreaterThan(40)
  await body.evaluate(el => { el.scrollTop = el.scrollHeight })
  await expect(page.locator('.tiptap p').last()).toBeInViewport()
  await screenshot('detail-mobile-320-short')
  await page.setViewportSize({ width: 320, height: 900 })
  await page.evaluate(() => { window.workspaceFixture.metadataRequests.length = 0 })
  const properties = page.getByRole('dialog', { name: '文档属性', exact: true })
  await page.getByRole('button', { name: '文档属性', exact: true }).click()
  await properties.getByRole('combobox', { name: '优先级', exact: true }).click()
  await page.getByRole('option', { name: '低', exact: true }).click()
  expect(await page.evaluate(() => window.workspaceFixture.metadataRequests.filter(r => r.method === 'PATCH').length)).toBe(0)
  await properties.getByRole('button', { name: '取消', exact: true }).click()
  expect(await page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('high')
  await page.getByRole('button', { name: '文档属性', exact: true }).click()
  await properties.getByRole('combobox', { name: '优先级', exact: true }).click()
  await page.getByRole('option', { name: '低', exact: true }).click()
  await page.evaluate(() => window.workspaceFixture.failMetadata())
  await properties.getByRole('button', { name: '确认保存属性' }).click()
  await expect(properties).toBeHidden()
  await expect(page.locator('.requirement-meta-error')).toContainText('当前选择尚未生效')
  await page.getByRole('button', { name: '文档属性', exact: true }).click()
  await expect(properties.getByRole('alert')).toContainText('选择尚未保存')
  await expect(properties.getByRole('combobox', { name: '优先级', exact: true })).toContainText('低')
  await properties.getByRole('button', { name: '确认保存属性' }).click()
  await expect(properties).toBeHidden()
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('low')
  expect(await page.evaluate(() => window.workspaceFixture.metadataRequests.filter(r => r.method === 'PATCH').length)).toBe(2)
  expect(await page.evaluate(() => JSON.stringify(window.workspaceFixture.document()) === window.layoutBody)).toBe(true)
  await page.getByRole('tab', { name: '版本比较', exact: true }).click()
  await expect(page.locator('.rich-diff')).toHaveClass(/rich-diff--unified/)
  await page.setViewportSize({ width: 1001, height: 1000 })
  await expect(page.locator('.rich-diff')).toHaveClass(/rich-diff--unified/)
  await page.getByRole('tab', { name: '并排', exact: true }).click()
  await page.setViewportSize({ width: 960, height: 1000 })
  await expect(page.locator('.rich-diff')).not.toHaveClass(/rich-diff--unified/)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(page.getByRole('combobox', { name: '优先级', exact: true })).toBeDisabled()
  await screenshot('detail-diff-1440')
  await page.getByRole('tab', { name: '正文', exact: true }).click()
  expect(await page.evaluate(() => window.layoutEditor === document.querySelector('.tiptap'))).toBe(true)
  await page.goto(url)
  await expect(page.getByRole('button', { name: /^段落样式：/ })).toBeVisible()
  const paragraph = page.locator('.tiptap p').first()
  await paragraph.click()
  await page.getByRole('button', { name: /^段落样式：/ }).click()
  await page.getByRole('menuitemradio', { name: '二级标题', exact: true }).click()
  await expect(page.locator('.tiptap h2').first()).toContainText('章节 1 的第 1 段')
  await page.getByRole('button', { name: /^段落样式：/ }).click()
  await page.getByRole('menuitemradio', { name: '普通正文', exact: true }).click()
  await expect(page.locator('.tiptap p').first()).toContainText('章节 1 的第 1 段')
  console.log('详情无头验证通过：桌面单行操作栏、长姓名多选、属性保存失败重试、确认提交、段落样式、320–560px 面板、920px 停靠边界、阅读锚点与编辑器保留、按可用宽度比较。')
}
