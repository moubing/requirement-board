import { expect } from '@playwright/test'

export async function verifyAccountExperience(page, url, screenshot) {
  await page.addInitScript(() => {
    window.accountClipboard = []
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: {
      writeText: async value => {
        if (window.accountClipboardBlocked) throw new Error('clipboard denied')
        window.accountClipboard.push(value)
      },
    } })
  })
  const visit = suffix => page.goto(url + '?page=consumer-accounts&panel=account' + (suffix ?? ''))
  const tabs = page.getByRole('tablist', { name: '凭证状态筛选' })
  const credentials = page.locator('.agent-credentials')
  const createButton = () => credentials.getByRole('button', { name: '创建凭证', exact: true })
  const keyboardClick = async target => { await expect(target).toBeEnabled(); await target.focus(); await expect(target).toBeFocused(); await page.keyboard.press('Enter') }
  // 以真实工作台的面板边界作参照，宽屏不再保留居中限宽和多余标题行。
  await page.setViewportSize({ width: 1920, height: 980 })
  await page.goto(url + '?page=dashboard')
  await expect(page.locator('.flow-board')).toBeVisible()
  const workbenchLeft = await page.locator('.desk-island--flow').boundingBox()
  const workbenchRight = await page.locator('.desk-island--activity').boundingBox()
  await visit('&tokenFixture=dense')
  await expect(page.locator('.agent-token-table tbody tr[data-row-index]')).toHaveCount(2)
  const profileBounds = await page.locator('.account-profile-banner').boundingBox()
  const securityBounds = await page.locator('.account-security').boundingBox()
  expect(Math.abs(profileBounds.x - workbenchLeft.x)).toBeLessThanOrEqual(1)
  expect(Math.abs(profileBounds.y - workbenchLeft.y)).toBeLessThanOrEqual(1)
  expect(Math.abs(securityBounds.x + securityBounds.width - workbenchRight.x - workbenchRight.width)).toBeLessThanOrEqual(1)
  await expect(page.locator('.account-home .account-card')).toHaveCount(4)
  await expect(page.getByRole('navigation', { name: '账号页分区' })).toHaveCount(0)
  // 引导尚未完成时，也应将资料、安全、完整引导和常用凭证放进桌面首屏。
  for (const [width, height] of [[1920, 980], [1440, 900], [1366, 768], [1280, 800]]) {
    await page.setViewportSize({ width, height })
    await page.locator('.app-page-scroll > .bing-scrollbar__viewport').evaluate(node => node.scrollTo({ top: 0 }))
    const layout = await page.locator('.app-page-scroll > .bing-scrollbar__viewport').evaluate(node => ({ height: node.clientHeight, content: node.scrollHeight }))
    await expect(page.locator('.account-profile-banner')).toBeInViewport({ ratio: 1 })
    await expect(page.locator('.account-security')).toBeInViewport({ ratio: 1 })
    await expect(credentials.locator('.agent-token-note')).toBeInViewport({ ratio: 1 })
    await expect(credentials.locator('.agent-version-note')).toBeInViewport({ ratio: 1 })
    await expect(page.locator('.agent-collaboration > .account-hint')).toBeInViewport({ ratio: 1 })
    await expect(page.getByRole('button', { name: '撤销 工作电脑 1', exact: true })).toBeInViewport({ ratio: 1 })
    await expect(page.getByRole('link', { name: '下载 Skill', exact: true })).toBeInViewport({ ratio: 1 })
    expect(layout.content - layout.height, width + 'px 桌面首屏').toBeLessThanOrEqual(1)
    expect(await page.locator('.agent-token-table .bing-scrollbar__viewport').first().evaluate(node => node.scrollWidth - node.clientWidth), width + 'px 凭证表格横向溢出').toBeLessThanOrEqual(1)
    await screenshot('account-compact-' + width + '-' + height)
    await tabs.getByRole('tab', { name: '已过期 (13)', exact: true }).click()
    await expect(page.locator('.agent-token-table tbody tr[data-row-index]')).toHaveCount(10)
    await expect(page.locator('.agent-token-table .bing-table__pagination')).toBeInViewport({ ratio: 1 })
    expect(await page.locator('.app-page-scroll > .bing-scrollbar__viewport').evaluate(node => node.scrollHeight - node.clientHeight), width + 'px 分页首屏').toBeLessThanOrEqual(1)
    const tableViewport = page.locator('.agent-token-table .bing-scrollbar__viewport').first()
    expect(await tableViewport.evaluate(node => node.scrollHeight - node.clientHeight)).toBeGreaterThan(0)
    expect(await tableViewport.evaluate(node => node.scrollWidth - node.clientWidth), width + 'px 分页表格横向溢出').toBeLessThanOrEqual(1)
    await tableViewport.evaluate(node => { node.scrollTop = node.scrollHeight })
    await expect(page.locator('.agent-token-table tbody tr[data-row-index]').last()).toBeInViewport({ ratio: 1 })
    await screenshot('account-compact-pagination-' + width + '-' + height)
    await tabs.getByRole('tab', { name: '有效 (2)', exact: true }).click()
    await expect(page.locator('.agent-token-table tbody tr[data-row-index]')).toHaveCount(2)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await visit('&initialAccountLoading=1&slowTokens=1')
  await expect(page.getByRole('status', { name: '正在加载凭证' })).toBeVisible()
  await expect(tabs.getByRole('tab', { name: '有效 (0)', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.account-profile-banner')).toContainText('@fixture.user')
  await expect(page.locator('.account-profile-banner')).toContainText('member@example.test')
  expect(await page.locator('.account-avatar').evaluate(node => [node.clientWidth, node.clientHeight, getComputedStyle(node).color])).toEqual([64, 64, 'rgb(51, 102, 204)'])
  await expect(page.getByText('进入工作台', { exact: true })).toHaveCount(0)
  await expect(page.getByText('可访问项目', { exact: true })).toHaveCount(0)
  await expect(page.locator('.agent-token-empty')).toContainText('还没有凭证')
  await expect(page.locator('.agent-setup li').first()).not.toHaveClass(/is-complete/)
  await keyboardClick(page.getByRole('button', { name: '复制用户名', exact: true }))
  await expect(page.getByRole('button', { name: '用户名已复制' })).toBeVisible()
  expect(await page.evaluate(() => window.accountClipboard.at(-1))).toBe('fixture.user')
  await expect(page.getByRole('button', { name: '复制用户名', exact: true })).toBeVisible()

  for (const action of ['安装', '更新', '卸载']) {
    const button = page.getByRole('button', { name: '复制' + action + '说明', exact: true })
    await keyboardClick(button)
    await expect(button).toHaveText('已复制')
    expect(await page.evaluate(() => window.accountClipboard.at(-1))).toContain('/api/agent/setup')
  }
  await expect(page.locator('.agent-setup li').nth(1)).toHaveClass(/is-complete/)
  await keyboardClick(createButton())
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('textbox', { name: '凭证名称', exact: true })).toBeFocused()
  await expect(dialog.getByRole('tab', { name: '30 天', exact: true })).toHaveAttribute('aria-selected', 'true')
  await dialog.getByRole('textbox', { name: '凭证名称', exact: true }).fill('我的笔记本')
  await keyboardClick(dialog.getByRole('tab', { name: '7 天', exact: true }))
  await keyboardClick(dialog.getByRole('button', { name: '创建凭证', exact: true }))
  await expect(dialog).toHaveAccessibleName('凭证已创建')
  await expect(dialog).toContainText('只显示这一次')
  expect(await page.evaluate(() => window.workspaceFixture.consumerAccounts.requests.find(item => item.method === 'POST').body.expiresInDays)).toBe(7)
  await keyboardClick(dialog.getByRole('button', { name: '复制凭证' }))
  await expect(dialog.getByRole('button', { name: '复制凭证' })).toHaveText('已复制')
  await page.evaluate(() => { window.accountClipboardBlocked = true })
  await dialog.getByRole('button', { name: '复制凭证' }).click()
  await expect(dialog.getByRole('alert')).toContainText('手动复制')
  await expect(dialog.getByRole('textbox', { name: '新建 AI 凭证' })).toHaveValue('fixture-only-not-a-valid-token')
  await page.evaluate(() => { window.accountClipboardBlocked = false })
  await keyboardClick(dialog.getByRole('button', { name: '完成', exact: true }))
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.agent-setup li').first()).toHaveClass(/is-complete/)
  await expect(tabs.getByRole('tab', { name: '有效 (1)', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.agent-expiry-warning')).toContainText('有凭证即将到期')
  await expect(page.locator('.agent-token-table')).toContainText('剩 7 天')
  await expect(page.locator('.agent-token-table .bing-table__pagination')).toHaveCount(0)
  await keyboardClick(createButton())
  await expect(dialog.getByRole('textbox', { name: '新建 AI 凭证' })).toHaveCount(0)
  await expect(dialog.getByRole('textbox', { name: '凭证名称' })).toHaveValue('')
  await keyboardClick(dialog.getByRole('tab', { name: '自定义', exact: true }))
  await dialog.getByRole('spinbutton', { name: '自定义有效期（天）' }).fill('5')
  await keyboardClick(dialog.getByRole('button', { name: '取消', exact: true }))
  await expect(dialog).toHaveCount(0)
  await keyboardClick(page.getByRole('button', { name: '我已完成调用', exact: true }))
  const guideToggle = page.getByRole('button', { name: '已配置，查看使用说明', exact: true })
  await expect(guideToggle).toHaveAttribute('aria-expanded', 'false')
  await expect(guideToggle).toBeFocused()
  await keyboardClick(guideToggle)
  await expect(page.locator('.agent-setup')).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('rb-agent-onboarding:fixture-user')))).toEqual({ version: 1, installCopied: true, usageConfirmed: true })
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('fixture-only-not-a-valid-token')

  await page.evaluate(() => { window.accountClipboardBlocked = true })
  await page.getByRole('button', { name: '复制更新说明', exact: true }).click()
  await expect(page.locator('.agent-collaboration [role="alert"]')).toContainText('手动复制')
  await page.evaluate(() => { window.accountClipboardBlocked = false })

  // 密码建议和双向实时匹配不改变既有 6–128 字符的准入规则。
  const passwordRequests = []
  await page.route('**/api/auth/change-password', async route => {
    passwordRequests.push(route.request().postDataJSON())
    await route.fulfill({ json: { token: null, user: { id: 'fixture-user' } } })
  })
  await keyboardClick(page.locator('.account-security').getByRole('button', { name: '修改密码', exact: true }))
  dialog = page.getByRole('dialog', { name: '修改密码', exact: true })
  await dialog.getByRole('textbox', { name: '当前密码', exact: true }).fill('fixture-password')
  await dialog.getByRole('textbox', { name: '新密码', exact: true }).fill('abcdef')
  await expect(dialog.locator('.account-password-strength')).toContainText('偏弱')
  await dialog.getByRole('textbox', { name: '确认新密码', exact: true }).fill('abcdex')
  await expect(dialog.getByText('两次输入的新密码不一致', { exact: true })).toBeVisible()
  await dialog.getByRole('textbox', { name: '新密码', exact: true }).fill('abcdex')
  await expect(dialog.getByText('两次输入一致', { exact: true })).toBeVisible()
  await keyboardClick(dialog.getByRole('button', { name: '保存新密码' }))
  await expect(dialog).toContainText('密码已修改')
  expect(passwordRequests).toEqual([{ currentPassword: 'fixture-password', newPassword: 'abcdex', revokeOtherSessions: true }])
  await keyboardClick(dialog.getByRole('button', { name: '完成', exact: true }))
  await expect(dialog).toHaveCount(0)
  await page.unroute('**/api/auth/change-password')

  await visit('&tokenFixture=dense')
  await expect(guideToggle).toHaveAttribute('aria-expanded', 'false')
  await expect(tabs.getByRole('tab', { name: '有效 (2)', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(tabs.getByRole('tab', { name: '已过期 (13)', exact: true })).toBeVisible()
  await expect(tabs.getByRole('tab', { name: '已撤销 (3)', exact: true })).toBeVisible()
  await tabs.getByRole('tab', { name: '已过期 (13)', exact: true }).click()
  await expect(page.locator('.agent-token-table tbody tr[data-row-index]')).toHaveCount(10)
  await expect(page.locator('.agent-token-table')).toContainText('历史凭证')
  await expect(page.locator('.agent-token-table .bing-table__pagination')).toBeVisible()
  await tabs.getByRole('tab', { name: '已撤销 (3)', exact: true }).click()
  await expect(page.locator('.agent-token-table tbody tr[data-row-index]')).toHaveCount(3)
  await expect(page.locator('.agent-token-table .bing-table__pagination')).toHaveCount(0)
  await tabs.getByRole('tab', { name: '有效 (2)', exact: true }).click()
  await expect(page.locator('.agent-token-table tbody tr[data-row-index]')).toHaveCount(2)
  await keyboardClick(page.getByRole('button', { name: '撤销 工作电脑 1', exact: true }))
  dialog = page.getByRole('dialog', { name: '撤销凭证', exact: true })
  await expect(dialog).toContainText('工作电脑 1')
  await expect(dialog).toContainText('撤销后使用该凭证的 AI 将立即失去访问权限')
  await keyboardClick(dialog.getByRole('button', { name: '取消', exact: true }))
  await expect(dialog).toHaveCount(0)
  await keyboardClick(page.getByRole('button', { name: '撤销 工作电脑 1', exact: true }))
  await keyboardClick(dialog.getByRole('button', { name: '确认撤销', exact: true }))
  await expect(tabs.getByRole('tab', { name: '有效 (1)', exact: true })).toBeVisible()
  await expect(tabs.getByRole('tab', { name: '已撤销 (4)', exact: true })).toBeVisible()

  // 布局和主题：检查实际滚动容器及各个交互区域，避免只检查 body。
  for (const close of await page.getByRole('button', { name: '关闭消息', exact: true }).all()) await close.click()
  await guideToggle.click()
  for (const theme of ['light', 'dark']) {
    await page.locator('html').evaluate((node, theme) => node.dataset.bingTheme = theme, theme)
    for (const width of [1440, 1280, 960, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.locator('.app-page-scroll > .bing-scrollbar__viewport').evaluate(node => node.scrollTo({ top: 0 }))
      const overflow = await page.locator('.account-home').evaluate(node => node.scrollWidth - node.clientWidth)
      expect(overflow, '账号页溢出 ' + width).toBeLessThanOrEqual(1)
      if (width <= 640) {
        await expect(page.locator('.agent-token-table')).toBeHidden()
        await expect(page.locator('.agent-token-cards')).toBeVisible()
        expect(await page.locator('.agent-token-cards').evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
      }
      await screenshot('account-' + theme + '-' + width)
      await credentials.scrollIntoViewIfNeeded()
      await expect(tabs.getByRole('tab', { selected: true })).toBeInViewport()
      await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
      await screenshot('account-credentials-' + theme + '-' + width)
    }
  }
  await tabs.getByRole('tab', { name: '已过期 (13)', exact: true }).click()
  await expect(page.locator('.agent-token-cards li')).toHaveCount(10)
  await keyboardClick(page.getByRole('button', { name: '下一页', exact: true }))
  await expect(page.locator('.agent-token-cards li')).toHaveCount(3)
  await expect(page.locator('.agent-mobile-pagination [role="status"]')).toHaveText('2 / 2')
  await screenshot('account-mobile-pagination')
  await page.setViewportSize({ width: 1440, height: 800 })

  await visit('&failTokens=1')
  await expect(credentials.getByRole('alert')).toBeVisible()
  await expect(page.locator('.account-security').getByRole('button', { name: '修改密码', exact: true })).toBeEnabled()
  await credentials.getByRole('button', { name: '重试加载凭证' }).click()
  await expect(tabs.getByRole('tab', { name: '有效 (0)', exact: true })).toBeVisible()
  await visit('&tokenFixture=limit')
  await expect(tabs.getByRole('tab', { name: '有效 (10)', exact: true })).toBeVisible()
  await expect(createButton()).toBeDisabled()
  await page.evaluate(() => {
    window.workspaceFixture.useAccountAccessState().value = { ...window.workspaceFixture.useAccountAccessState().value, user: { ...window.workspaceFixture.useAccountAccessState().value.user, id: 'other-user' } }
  })
  await expect(page.locator('.agent-setup')).toBeVisible()
  await expect(page.locator('.agent-setup li').nth(1)).not.toHaveClass(/is-complete/)

  // 安装时先停住时钟，再加载页面，确保组件的真实定时器也由时钟控制。
  await page.clock.install()
  await visit('&pendingAccount=1')
  await expect(page.locator('.account-approval-steps')).toContainText('等待审批')
  await expect(page.locator('#account-ai')).toHaveCount(0)
  const accessRequests = () => page.evaluate(() => window.workspaceFixture.consumerAccounts.requests.filter(item => item.url === '/api/account/access').length)
  await page.evaluate(() => Object.defineProperty(document, 'visibilityState', { configurable: true, get: () => window.accountVisibility ?? 'visible' }))
  await page.getByRole('textbox', { name: '加入说明（选填）' }).fill('尚未提交的说明')
  await page.evaluate(() => { window.accountVisibility = 'hidden' })
  await page.clock.fastForward(60_000)
  expect(await accessRequests()).toBe(0)
  await page.evaluate(() => { window.accountVisibility = 'visible'; window.workspaceFixture.consumerAccounts.access.request = { ...window.workspaceFixture.consumerAccounts.access.request, status: 'rejected', reviewNote: '请补充团队信息' } })
  await page.clock.fastForward(60_000)
  await expect(page.locator('.account-approval-steps .is-rejected')).toContainText('申请被拒绝')
  await expect(page.getByText('管理员回复：请补充团队信息')).toBeVisible()
  await expect(page.getByRole('textbox', { name: '加入说明（选填）' })).toHaveValue('尚未提交的说明')
  await screenshot('account-approval-rejected')
  await page.getByRole('button', { name: '重新申请加入', exact: true }).click()
  await expect(page.locator('.account-approval-steps')).toContainText('等待审批')
  await page.evaluate(() => { window.workspaceFixture.consumerAccounts.access.canAccessProject = true; window.workspaceFixture.consumerAccounts.access.projectRoles = ['developer'] })
  await page.clock.fastForward(60_000)
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.navigationRequests)).toContain('/')
  const countAfterApproval = await accessRequests()
  await page.clock.fastForward(120_000)
  expect(await accessRequests()).toBe(countAfterApproval)
  await visit('&pendingAccount=1')
  await page.evaluate(() => {
    window.workspaceFixture.consumerAccounts.access.canAccessProject = true
    window.workspaceFixture.operations.failures.navigation = 1
  })
  await page.getByRole('button', { name: '刷新审批状态', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '请刷新页面后进入项目' })).toBeVisible()
  await expect(page.locator('.account-approval')).toHaveCount(0)
  await page.evaluate(() => window.workspaceFixture.unmount())
  const countAfterUnmount = await page.evaluate(() => window.workspaceFixture.consumerAccounts.requests.length)
  await page.clock.fastForward(120_000)
  expect(await page.evaluate(() => window.workspaceFixture.consumerAccounts.requests.length)).toBe(countAfterUnmount)
  console.log('REQ-53 通过：工作台同边界的四卡片布局、无冗余页内导航、1280×800/1366×768/1440×900/1920×980 首屏和表格内滚动、横幅/头像/复制、独立骨架与失败重试、密码实时校验、三步引导和账号隔离、凭证总数/筛选/分页/到期/创建/撤销/一次性明文、键盘操作、320–1440px 亮暗布局、前台审批轮询/拒绝/重申/通过跳转/卸载清理。')
}
