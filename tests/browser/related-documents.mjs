import { expect } from '@playwright/test'

export async function verifyRelatedDocuments(page, screenshot) {
  const section = page.getByRole('region', { name: '关联文档', exact: true })
  const dialog = page.getByRole('dialog', { name: '添加关联文档', exact: true })
  const add = () => section.getByRole('button', { name: '添加关联文档', exact: true }).click()
  const count = section.locator('.related-documents__count')
  await expect(count).toHaveText('1')
  await add()
  const query = dialog.getByRole('searchbox', { name: '搜索关联文档', exact: true })
  await expect(dialog.getByRole('checkbox', { name: 'REQ-10 编辑器图片与表格交互，已关联', exact: true })).toBeDisabled()
  await query.fill('工作区布局优化')
  await expect(dialog.getByText('没有找到相关文档，试试其他关键词或编号。', { exact: true })).toBeVisible()
  await query.fill('状态')
  await dialog.getByText('完善文档的状态流转', { exact: true }).click()
  await query.fill('REQ-8')
  await dialog.getByText('项目成员与角色说明', { exact: true }).click()
  await expect(dialog.getByText('已选择 2 篇', { exact: true })).toBeVisible()
  await query.fill('')
  await expect(dialog.getByRole('checkbox', { name: 'REQ-11 完善文档的状态流转', exact: true })).toBeChecked()
  await screenshot('related-documents-picker')
  await page.evaluate(() => window.workspaceFixture.failRelation())
  await dialog.getByRole('button', { name: '确认关联（2）', exact: true }).click()
  await expect(dialog).toBeHidden()
  await section.getByRole('button', { name: '重试添加关联', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('关联保存失败，请重试。')
  await expect(dialog.getByText('已选择 2 篇', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '确认关联（2）', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(count).toHaveText('3')
  await screenshot('related-documents-list')
  await add()
  await expect(dialog.getByRole('checkbox', { name: 'REQ-11 完善文档的状态流转，已关联', exact: true })).toBeDisabled()
  await dialog.getByText('文档目录与版本比较', { exact: true }).click()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(count).toHaveText('3')

  const link = section.getByRole('link', { name: 'REQ-11 完善文档的状态流转（在新标签页打开）', exact: true })
  await expect(link).toHaveAttribute('target', '_blank')
  await expect(link).toHaveAttribute('rel', /noopener/)
  const popupPromise = page.waitForEvent('popup')
  await link.click()
  const popup = await popupPromise
  try { await expect(popup).toHaveURL(/\/requirements\/fixture-1$/) } finally { await popup.close() }

  await section.getByRole('button', { name: 'REQ-11 更多操作', exact: true }).click()
  await page.evaluate(() => window.workspaceFixture.failRelation())
  await page.getByRole('menuitem', { name: '解除关联', exact: true }).click()
  await expect(section.getByRole('alert')).toHaveText('关联保存失败，请重试。')
  await expect(count).toHaveText('3')
  await section.getByRole('button', { name: 'REQ-11 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '解除关联', exact: true }).click()
  await expect(count).toHaveText('2')
  await section.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(count).toHaveText('3')
  await page.evaluate(() => { window.workspaceFixture.draft.readOnly.value = true })
  await expect(section.getByRole('button', { name: '添加关联文档', exact: true })).toBeDisabled()
  await page.evaluate(() => { window.workspaceFixture.draft.readOnly.value = false })

  for (const key of ['REQ-11', 'REQ-10', 'REQ-8']) {
    await section.getByRole('button', { name: `${key} 更多操作`, exact: true }).click()
    await page.getByRole('menuitem', { name: '解除关联', exact: true }).click()
  }
  await expect(section.getByText('还没有关联文档', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开文档信息和目录', exact: true }).click()
  await add()
  await expect(dialog).toBeVisible()
  await screenshot('related-documents-mobile')
  await page.setViewportSize({ width: 320, height: 760 })
  // 跨断点会收起父抽屉；在新的窄屏尺寸重新打开验证嵌套弹窗。
  if (!await dialog.isVisible()) {
    await page.getByRole('button', { name: '打开文档信息和目录', exact: true }).click()
    await add()
  }
  const box = await dialog.boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(320)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('dialog', { name: '文档辅助面板', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 2312, height: 1200 })
  await page.evaluate(() => window.workspaceFixture.resetRelations())
  await expect(count).toHaveText('1')
}
