import { expect } from '@playwright/test'

export async function verifyOperationFeedback(page, url) {
  const setDelay = (key, ms) => page.evaluate(([key, ms]) => { window.workspaceFixture.operations.delays[key] = ms }, [key, ms])
  const fail = key => page.evaluate(key => { window.workspaceFixture.operations.failures[key] = 1 }, key)
  const clear = () => page.evaluate(() => window.workspaceFixture.clearToasts())
  const notifications = () => page.evaluate(() => window.workspaceFixture.toasts())
  const priority = page.getByRole('combobox', { name: '优先级', exact: true })
  const owners = page.getByRole('combobox', { name: '负责人', exact: true })
  const search = page.getByRole('combobox', { name: '搜索文档号或名称', exact: true })
  const patchKey = 'PATCH:/api/requirements/fixture'
  await setDelay(patchKey, 2000)
  await page.evaluate(() => {
    window.disabledChanges = []
    window.disabledObserver = new MutationObserver(records => {
      for (const record of records) if (record.target.disabled && ['优先级', '修改文档状态', '搜索文档号或名称'].includes(record.target.getAttribute('aria-label'))) window.disabledChanges.push(record.target.getAttribute('aria-label'))
    })
    window.disabledObserver.observe(document.body, { subtree: true, attributes: true, attributeFilter: ['disabled'] })
  })
  await owners.click()
  await page.getByRole('option', { name: '成员乙', exact: true }).click()
  expect((await notifications()).filter(item => item.type === 'loading' && item.message.includes('负责人：'))).toHaveLength(1)
  await page.getByRole('option', { name: '成员丙', exact: true }).click()
  await page.getByRole('option', { name: '成员乙', exact: true }).click()
  await expect(priority).toBeEnabled()
  await expect(page.getByRole('button', { name: '修改文档状态' })).toBeEnabled()
  await expect(search).toBeEnabled()
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.assigneeIds)).toEqual(['fixture-user', 'member-c'])
  await expect(page.getByRole('option', { name: '成员丙', exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.disabledChanges)).toEqual([])
  await page.keyboard.press('Escape')
  await clear()
  await priority.click(); await page.getByRole('option', { name: '低', exact: true }).click()
  await priority.click(); await page.getByRole('option', { name: '中', exact: true }).click()
  await owners.click(); await page.getByRole('option', { name: '成员乙', exact: true }).click(); await page.keyboard.press('Escape')
  const changingFields = (await notifications()).filter(item => item.type === 'loading')
  expect(changingFields).toHaveLength(2)
  expect(new Set(changingFields.map(item => item.id)).size).toBe(2)
  expect(changingFields.some(item => item.message.includes('负责人：'))).toBe(true)
  expect(changingFields.some(item => item.message.includes('优先级：'))).toBe(true)
  await search.fill('请求期间仍可输入')
  await expect(search).toBeFocused()
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('medium')
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.assigneeIds)).toEqual(['fixture-user', 'member-c', 'member-b'])
  await expect(search).toHaveValue('请求期间仍可输入')
  const fieldResults = (await notifications()).filter(item => item.type === 'success')
  expect(fieldResults).toHaveLength(2)
  expect(fieldResults.map(item => item.id).sort()).toEqual(changingFields.map(item => item.id).sort())
  await expect(search).toBeFocused()
  expect(await page.evaluate(() => window.disabledChanges)).toEqual([])
  await page.evaluate(() => window.disabledObserver.disconnect())
  await search.fill(''); await search.press('Escape')
  await setDelay(patchKey, 0)

  await clear(); await setDelay(patchKey, 2000)
  await owners.click(); await page.getByRole('option', { name: '成员乙', exact: true }).click(); await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '修改文档状态', exact: true }).click()
  await page.getByRole('menuitemradio', { name: '进行中', exact: true }).click()
  const ownerAndStatus = (await notifications()).filter(item => item.type === 'loading')
  expect(ownerAndStatus).toHaveLength(2)
  expect(ownerAndStatus.some(item => item.message.includes('负责人：'))).toBe(true)
  expect(ownerAndStatus.some(item => item.message.includes('状态：进行中'))).toBe(true)
  await expect(page.getByRole('status', { name: '当前状态', exact: true })).toHaveText('进行中')
  expect((await notifications()).filter(item => item.type === 'success')).toHaveLength(2)
  await setDelay(patchKey, 0)
  await fail(patchKey)
  await priority.click(); await page.getByRole('option', { name: '高', exact: true }).click()
  await expect(page.locator('.requirement-meta-error')).toContainText('优先级的当前选择尚未生效')
  await expect(priority).toContainText('高优先级')
  await page.getByRole('button', { name: '重试保存属性' }).click()
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('high')
  await expect(page.locator('.requirement-meta-error')).toBeHidden()

  // 侧栏移动后仍可在属性保存期间操作关联；较早的读取不能覆盖刚保存的属性。
  await page.getByRole('tab', { name: '文档信息', exact: true }).click()
  await setDelay(patchKey, 2000)
  await priority.click(); await page.getByRole('option', { name: '低', exact: true }).click()
  await expect(page.getByRole('region', { name: '文档常用属性', exact: true })).toHaveAttribute('aria-busy', 'true')
  await page.getByRole('region', { name: '关联文档', exact: true }).getByRole('button', { name: '添加关联文档', exact: true }).click()
  const related = page.getByRole('dialog', { name: '添加关联文档', exact: true })
  await expect(related).toBeVisible()
  await related.getByRole('button', { name: '取消', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('low')
  await setDelay(patchKey, 0)
  const detailReads = () => page.evaluate(() => window.workspaceFixture.metadataRequests.filter(request => request.method === 'GET' && request.url === '/api/requirements/fixture').length)
  const readsBefore = await detailReads()
  await setDelay('GET:/api/requirements/fixture', 2000)
  await page.evaluate(async () => {
    window.workspaceFixture.notifyProperties()
    await Promise.resolve()
    await Promise.resolve()
  })
  await priority.click(); await page.getByRole('option', { name: '高', exact: true }).click()
  await expect(priority).toContainText('高优先级')
  await expect.poll(detailReads, { timeout: 10_000 }).toBe(readsBefore + 2)
  await expect(priority).toContainText('高优先级')
  expect(await page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('high')
  await setDelay('GET:/api/requirements/fixture', 0)

  // 新布局内的取消入口必须经过页面反馈流程，成功后解除锁定提示。
  await clear(); await setDelay('release-lock', 1000)
  await page.evaluate(() => {
    const draft = window.workspaceFixture.draft
    draft.canReleaseLock.value = true
    draft.agentLock.value = { snapshotId: 'fixture-lock', userId: 'fixture-user', userName: '测试成员', expiresAt: new Date(Date.now() + 60_000).toISOString() }
  })
  const lock = page.getByRole('status', { name: 'AI 编辑锁定', exact: true })
  await lock.getByRole('button', { name: '取消 AI 编辑', exact: true }).click()
  await lock.getByRole('button', { name: '确认取消 AI 编辑', exact: true }).click()
  await expect(page.getByText('正在取消 REQ-TEST 的 AI 编辑', { exact: true })).toBeVisible()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'success' && item.message === 'REQ-TEST 的 AI 编辑已取消')).toBe(true)
  await expect(lock).toBeHidden()
  await page.getByRole('tab', { name: '目录', exact: true }).click()

  // 已完成的一轮保持原结果；下一次选择不能复用它的 Toast。
  await clear()
  await priority.click(); await page.getByRole('option', { name: '低', exact: true }).click()
  await expect.poll(async () => (await notifications()).filter(item => item.type === 'success').length).toBe(1)
  const previousRound = (await notifications())[0]
  await setDelay(patchKey, 2000)
  await priority.click(); await page.getByRole('option', { name: '中', exact: true }).click()
  expect(await notifications()).toContainEqual(previousRound)
  expect((await notifications()).some(item => item.id !== previousRound.id && item.type === 'loading')).toBe(true)
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('medium')

  // 一个字段失败后修改另一字段，旧失败提示保持独立，失败值仍由原队列重试。
  await clear(); await setDelay(patchKey, 0); await fail(patchKey)
  await priority.click(); await page.getByRole('option', { name: '高', exact: true }).click()
  await expect.poll(async () => (await notifications()).filter(item => item.type === 'error').length).toBe(1)
  const failedRound = (await notifications())[0]
  await setDelay(patchKey, 2000)
  await owners.click(); await page.getByRole('option', { name: '成员乙', exact: true }).click(); await page.keyboard.press('Escape')
  expect(await notifications()).toContainEqual(failedRound)
  expect((await notifications()).filter(item => item.type === 'loading')).toHaveLength(2)
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('high')
  await expect(page.locator('.requirement-meta-error')).toBeHidden()
  await setDelay(patchKey, 0)

  // 草稿准备、写入与列表刷新分别延迟；弹窗不等待任何网络阶段。
  await clear()
  await setDelay('prepare-version', 2000)
  const save = page.getByRole('dialog', { name: '保存正式版本', exact: true })
  await page.getByRole('button', { name: '保存版本', exact: true }).click()
  await save.getByRole('textbox', { name: '版本说明' }).fill('保留这次版本说明')
  await page.evaluate(() => { window.workspaceFixture.operations.loseResponses['POST:/api/requirements/fixture/revisions'] = 1 })
  await save.getByRole('button', { name: '确认保存版本' }).click()
  await expect(save).toBeHidden({ timeout: 700 })
  await expect(page.getByText('正在保存 REQ-TEST 的正式版本', { exact: true })).toBeVisible()
  await expect(search).toBeEnabled()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'error' && item.message.includes('保存版本未完成'))).toBe(true)
  await page.getByRole('button', { name: '保存版本', exact: true }).click()
  await expect(save.getByRole('textbox', { name: '版本说明' })).toHaveValue('保留这次版本说明')
  await fail('refresh:/api/requirements/fixture/revisions')
  await save.getByRole('button', { name: '确认保存版本' }).click()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'warning' && item.message.includes('操作已成功'))).toBe(true)
  expect(await page.evaluate(() => window.workspaceFixture.revisions.value.length)).toBe(4)
  const versionRequests = await page.evaluate(() => window.workspaceFixture.operations.requests.filter(item => item.key === 'POST:/api/requirements/fixture/revisions'))
  expect(versionRequests).toHaveLength(2)
  expect(versionRequests[0].body).toEqual(versionRequests[1].body)

  // 窄屏失败后重开保留选择，不抢回用户焦点。
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => document.documentElement.dataset.bingTheme = 'dark')
  await clear(); await fail(patchKey); await setDelay(patchKey, 2000)
  await page.getByRole('button', { name: '文档属性', exact: true }).click()
  const properties = page.getByRole('dialog', { name: '文档属性', exact: true })
  await properties.getByRole('combobox', { name: '优先级', exact: true }).click()
  await page.getByRole('option', { name: '低', exact: true }).click()
  await properties.getByRole('button', { name: '确认保存属性' }).click()
  await expect(properties).toBeHidden({ timeout: 700 })
  await expect.poll(async () => (await notifications()).some(item => item.type === 'error')).toBe(true)
  await page.getByRole('button', { name: '文档属性', exact: true }).click()
  await expect(properties.getByRole('combobox', { name: '优先级', exact: true })).toContainText('低')
  await properties.getByRole('button', { name: '确认保存属性' }).click()
  await expect.poll(() => page.evaluate(() => window.workspaceFixture.requirement.value.priority)).toBe('low')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => document.documentElement.dataset.bingTheme = 'light')

  // 创建响应丢失后用同一 ID 领取结果；重开表单则不自动跳走。
  await page.goto(url)
  const create = page.getByRole('dialog', { name: '新建文档', exact: true })
  await setDelay('POST:/api/requirements', 2000)
  await page.getByRole('button', { name: '新建文档', exact: true }).click()
  await create.getByRole('textbox', { name: '文档标题', exact: true }).fill('失败恢复的新文档')
  await page.evaluate(() => { window.workspaceFixture.operations.loseResponses['POST:/api/requirements'] = 1 })
  await create.getByRole('button', { name: '创建并编辑' }).click()
  await expect(create).toBeHidden({ timeout: 700 })
  await expect.poll(async () => (await notifications()).some(item => item.type === 'error')).toBe(true)
  await page.getByRole('button', { name: '继续创建', exact: true }).click()
  await expect(create.getByRole('textbox', { name: '文档标题', exact: true })).toHaveValue('失败恢复的新文档')
  await create.getByRole('button', { name: '创建并编辑' }).click()
  await expect(create).toBeHidden({ timeout: 700 })
  await page.getByRole('button', { name: '新建文档', exact: true }).click()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'success')).toBe(true)
  await expect(create).toBeVisible()
  expect(await page.evaluate(() => window.workspaceFixture.navigationRequests)).toEqual([])
  const creates = await page.evaluate(() => window.workspaceFixture.operations.requests.filter(item => item.key === 'POST:/api/requirements'))
  expect(creates).toHaveLength(2)
  expect(creates[0].headers).toEqual(creates[1].headers)
  await create.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('link', { name: '已创建：失败恢复的新文档' })).toBeVisible()

  // 自动导航失败时结果链接不能消失，用户仍可显式关闭。
  await page.goto(url)
  await fail('navigation')
  await page.getByRole('button', { name: '新建文档', exact: true }).click()
  await create.getByRole('textbox', { name: '文档标题', exact: true }).fill('导航失败仍可打开')
  await create.getByRole('button', { name: '创建并编辑' }).click()
  await expect(page.getByRole('link', { name: '已创建：导航失败仍可打开', exact: true })).toBeVisible()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'warning' && item.message.includes('暂时无法跳转'))).toBe(true)
  await page.getByRole('button', { name: '关闭创建结果提示', exact: true }).click()
  await expect(page.locator('.document-create-result')).toHaveCount(0)

  await page.goto(url)
  await setDelay('POST:/api/document-templates', 2000)
  await fail('POST:/api/document-templates')
  const template = page.getByRole('dialog', { name: '另存为模板', exact: true })
  const openTemplate = async () => {
    await page.getByRole('button', { name: '更多文档操作', exact: true }).click()
    await page.getByRole('menuitem', { name: '另存为模板', exact: true }).click()
  }
  await openTemplate()
  await template.getByRole('textbox', { name: '模板名称' }).fill('可恢复的模板')
  await template.getByRole('button', { name: '保存模板', exact: true }).click()
  await expect(template).toBeHidden({ timeout: 700 })
  await expect.poll(async () => (await notifications()).some(item => item.type === 'error')).toBe(true)
  await openTemplate()
  await expect(template.getByRole('textbox', { name: '模板名称' })).toHaveValue('可恢复的模板')
  await template.getByRole('button', { name: '保存模板', exact: true }).click()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'success')).toBe(true)

  await page.goto(`${url}?page=templates`)
  await page.getByRole('button', { name: '复制为新模板', exact: true }).click()
  await page.getByRole('textbox', { name: '模板名称', exact: true }).fill('管理页保存仍留在编辑器')
  await setDelay('POST:/api/document-templates', 2000)
  await page.getByRole('button', { name: '保存模板', exact: true }).click()
  await expect(page.locator('.tiptap')).toBeVisible()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'success')).toBe(true)
  await expect(page.getByRole('textbox', { name: '模板名称', exact: true })).toHaveValue('管理页保存仍留在编辑器')
  await expect(page.locator('.tiptap')).toBeVisible()

  await page.goto(`${url}?page=members`)
  const roles = page.getByRole('dialog', { name: '设置项目角色', exact: true })
  await setDelay('PUT:/api/members/fixture-user/roles', 2000)
  await fail('PUT:/api/members/fixture-user/roles')
  await page.getByRole('button', { name: '设置角色', exact: true }).first().click()
  await roles.getByText('开发', { exact: true }).click()
  await roles.getByRole('button', { name: '保存角色', exact: true }).click()
  await expect(roles).toBeHidden({ timeout: 700 })
  await page.getByRole('button', { name: '继续设置角色', exact: true }).click()
  await expect(roles.getByRole('checkbox', { name: '开发', exact: true })).toBeChecked()
  await roles.getByRole('button', { name: '保存角色', exact: true }).click()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'success')).toBe(true)

  await page.goto(`${url}?page=requests`)
  const review = page.getByRole('dialog', { name: '处理加入申请', exact: true })
  const reviewKey = 'POST:/api/admin/requests/request-fixture/review'
  await setDelay(reviewKey, 2000); await fail(reviewKey)
  await page.getByRole('button', { name: '审批', exact: true }).click()
  await review.getByText('拒绝申请', { exact: true }).click()
  await review.getByRole('textbox', { name: '拒绝原因', exact: true }).fill('保留审批原因')
  await review.getByRole('button', { name: '确认拒绝', exact: true }).click()
  await expect(review).toBeHidden({ timeout: 700 })
  await page.getByRole('button', { name: '继续处理申请', exact: true }).click()
  await expect(review.getByRole('textbox', { name: '拒绝原因', exact: true })).toHaveValue('保留审批原因')
  await review.getByRole('button', { name: '确认拒绝', exact: true }).click()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'success' && item.message.includes('已拒绝'))).toBe(true)

  await page.goto(`${url}?page=users`)
  const userDialog = page.getByRole('dialog', { name: '管理用户', exact: true })
  const userKey = 'POST:/api/admin/users/fixture-member-2/status'
  await setDelay(userKey, 2000); await fail(userKey)
  await page.getByRole('button', { name: '管理', exact: true }).nth(1).click()
  await userDialog.getByRole('button', { name: '停用账号', exact: true }).click()
  await userDialog.getByRole('textbox', { name: '停用原因', exact: true }).fill('保留停用原因')
  await userDialog.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect(userDialog).toBeHidden({ timeout: 700 })
  await page.getByRole('button', { name: '继续处理用户', exact: true }).click()
  await expect(userDialog.getByRole('textbox', { name: '停用原因', exact: true })).toHaveValue('保留停用原因')
  await userDialog.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect.poll(async () => (await notifications()).some(item => item.type === 'success' && item.message.includes('已完成'))).toBe(true)
  expect(await page.evaluate(() => window.workspaceFixture.operations.requests.filter(item => item.key.endsWith('/status')).map(item => item.body))).toEqual([
    { disabled: true, reason: '保留停用原因' }, { disabled: true, reason: '保留停用原因' },
  ])
  console.log('操作反馈无头验证通过：连续属性选择、响应丢失重试、刷新失败、窄屏、创建、模板、成员角色、审批和账号停用。')
}
